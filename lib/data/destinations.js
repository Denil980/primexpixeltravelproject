export function getDestinationById(id) {
    return destinations.find((d) => d.id.toLowerCase() === id.toLowerCase());
}
export function getPackagesForDestination(destId) {
    const dest = getDestinationById(destId);
    if (!dest)
        return [];
    return packages.filter((p) => p.destinationId.toLowerCase() === dest.id.toLowerCase() ||
        (dest.packageIds && dest.packageIds.includes(p.id)) ||
        p.destination.toLowerCase().includes(dest.city.toLowerCase()));
}
export function getPackageCountForDestination(destId) {
    return getPackagesForDestination(destId).length;
}
